#!/usr/bin/env node
// Builds the framework-free kit into public/kit (served at /kit):
//   pixelcn.js / pixelcn.min.js  ES module (src/kit/index.ts)
//   pixelcn.css                  themes, engine, role classes, fonts
//   fonts/                       the self-hosted font files
// and app/theme.css, the same engine CSS for the site.
// Committed like public/r, and CI checks it's up to date.
import { build } from "esbuild";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tmpdir } from "node:os";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(APP, "public", "kit");
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const banner = { js: "// pixelcn kit - https://pixelcn.vercel.app/kits/html (MIT). Generated by scripts/build-kit.mjs." };
const common = { absWorkingDir: APP, entryPoints: [join(APP, "src/kit/index.ts")], bundle: true, format: "esm", platform: "browser", target: "es2020", tsconfig: join(APP, "tsconfig.json"), banner, legalComments: "none", logLevel: "warning" };
await build({ ...common, outfile: join(OUT, "pixelcn.js") });
await build({ ...common, outfile: join(OUT, "pixelcn.min.js"), minify: true });

// CSS: run the same generator the site uses, with font URLs relative to the kit.
const tmp = join(tmpdir(), `pixelcn-kit-css-${process.pid}.mjs`);
await build({ entryPoints: [join(APP, "src/kit/css.ts")], bundle: true, format: "esm", platform: "node", outfile: tmp, tsconfig: join(APP, "tsconfig.json"), logLevel: "warning" });
const { buildKitCss, buildThemeCss } = await import(pathToFileURL(tmp).href);
rmSync(tmp);
const fontFaces = readFileSync(join(APP, "app", "fonts.css"), "utf8").replace(/\r\n/g, "\n").replace(/url\(\/fonts\//g, "url(./fonts/");
writeFileSync(join(OUT, "pixelcn.css"), buildKitCss(fontFaces) + "\n");
cpSync(join(APP, "public", "fonts"), join(OUT, "fonts"), { recursive: true });

// The site imports the same engine CSS (app/layout.tsx).
writeFileSync(join(APP, "app", "theme.css"), `/* Generated by scripts/build-kit.mjs from lib/pixel-engine.ts - do not edit. */\n${buildThemeCss()}\n`);

console.log("Kit built: public/kit (pixelcn.js, pixelcn.min.js, pixelcn.css, fonts/)");
